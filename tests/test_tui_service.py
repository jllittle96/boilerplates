"""Tests for the TUI service layer. They need no Textual, so they run in the normal CI."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from cli.core.library import Library
from cli.tui.service import TemplateService


class _Libs:
    """Minimal stand-in for LibraryManager that points at a temp library."""

    def __init__(self, root: Path) -> None:
        self.libraries = [Library("test", root, library_type="static")]

    def find(self, kind: str, sort_results: bool = False):
        return [(path, name, False) for path, name in self.libraries[0].find(kind, sort_results)]


class _Config:
    def __init__(self, defaults: dict | None = None) -> None:
        self._defaults = defaults or {}

    def get_defaults(self, kind: str) -> dict:
        return self._defaults


def _make_library(root: Path) -> None:
    tdir = root / "compose" / "demo"
    (tdir / "files").mkdir(parents=True)
    manifest = {
        "slug": "demo",
        "kind": "compose",
        "metadata": {"name": "Demo", "description": "Demo template"},
        "variables": [
            {
                "name": "general",
                "title": "General",
                "items": [
                    {"name": "host", "type": "str", "title": "Host", "default": "demo", "required": True},
                    {"name": "port", "type": "int", "title": "Port", "default": 8080},
                    {"name": "token", "type": "secret", "title": "Token", "config": {"autogenerated": True}},
                ],
            },
            {
                "name": "tls",
                "title": "TLS",
                "toggle": "tls_enabled",
                "items": [
                    {"name": "tls_enabled", "type": "bool", "title": "Enable TLS", "default": False},
                    {"name": "tls_domain", "type": "str", "title": "Domain", "default": "example.org"},
                ],
            },
        ],
    }
    (tdir / "template.json").write_text(json.dumps(manifest), encoding="utf-8")
    (tdir / "files" / "compose.yaml").write_text(
        "name: <<host>>\nport: <<port>>\ntoken: <<token>>\n<% if tls_enabled %>tls: <<tls_domain>>\n<% endif %>",
        encoding="utf-8",
    )


@pytest.fixture
def session(tmp_path: Path):
    _make_library(tmp_path)
    svc = TemplateService(libraries=_Libs(tmp_path), config=_Config({"port": 9000}))
    template = svc.templates("compose")[0]
    return svc.open("compose", template)


def test_lists_templates(tmp_path: Path) -> None:
    _make_library(tmp_path)
    svc = TemplateService(libraries=_Libs(tmp_path), config=_Config())
    assert [t.id for t in svc.templates("compose")] == ["demo"]


def test_saved_defaults_are_applied(session) -> None:
    assert session.variable("port").value == 9000


def test_invalid_input_returns_message_and_keeps_old_value(session) -> None:
    assert "integer" in session.set_value("port", "abc")
    assert session.variable("port").value == 9000


def test_toggle_hides_dependent_variable_until_enabled(session) -> None:
    section = next(s for s in session.sections() if s.key == "tls")
    domain = session.variable("tls_domain")
    toggle = session.variable("tls_enabled")
    assert session.variable_visible(section, toggle)
    assert not session.variable_visible(section, domain)
    session.set_value("tls_enabled", True)
    assert session.variable_visible(section, domain)


def test_render_reflects_edits_and_conditionals(session) -> None:
    first = session.render()
    assert first.ok and "tls:" not in first.files["compose.yaml"]
    session.set_value("tls_enabled", True)
    assert "tls: example.org" in session.render().files["compose.yaml"]


def test_autogenerated_secret_is_stable_between_renders(session) -> None:
    a = session.render().files["compose.yaml"]
    b = session.render().files["compose.yaml"]
    assert a == b


def test_required_field_blocks_render(session) -> None:
    session.set_value("host", "")
    assert not session.render().ok


def test_write_creates_files_and_refuses_path_escape(session, tmp_path: Path) -> None:
    result = session.render()
    out = tmp_path / "out"
    session.write(out, result.files)
    assert (out / "compose.yaml").exists()
    assert session.conflicts(out, result.files) == ["compose.yaml"]
    with pytest.raises(ValueError):
        session.write(out, {"../evil.txt": "x"})
